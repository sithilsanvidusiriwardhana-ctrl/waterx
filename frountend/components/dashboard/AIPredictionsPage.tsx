"use client";

import { useCallback, useEffect, useState } from "react";
import { AlertCircle, BrainCircuit, Database, RefreshCw, TrendingDown } from "lucide-react";
import { AIPredictionChart } from "@/components/dashboard/Charts";
import { getDashboard, type DashboardSnapshot } from "@/lib/api";

function formatTime(value: string) {
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? value
    : date.toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" });
}

export function AIPredictionsPage() {
  const [snapshot, setSnapshot] = useState<DashboardSnapshot | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const refresh = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      setSnapshot(await getDashboard());
    } catch (requestError) {
      setError(requestError instanceof Error ? requestError.message : "Prediction data could not be loaded.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    let active = true;
    getDashboard()
      .then((data) => {
        if (active) {
          setSnapshot(data);
          setError("");
        }
      })
      .catch((requestError: unknown) => {
        if (active) {
          setError(requestError instanceof Error ? requestError.message : "Prediction data could not be loaded.");
        }
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => {
      active = false;
    };
  }, []);

  const predictions = snapshot?.predictions ?? [];
  const evaluatedCount = predictions.filter((prediction) => prediction.actualMoisture !== null).length;
  const latestPrediction = predictions[0] ?? null;
  const mlPipeline = snapshot?.mlPipeline;

  return (
    <div className="dashboard-content ml-page">
      <header className="page-heading ml-page-heading">
        <div>
          <p className="eyebrow">WATERX MODEL OUTPUT</p>
          <h1>AI Predictions</h1>
          <p className="page-subtitle">Saved moisture forecasts from the backend simulation</p>
        </div>
        <button className="button secondary ml-refresh" type="button" onClick={() => { void refresh(); }} disabled={loading}>
          <RefreshCw size={14} className={loading ? "ml-spinning" : ""} />
          {loading ? "Refreshing…" : "Refresh"}
        </button>
      </header>

      <div className="ml-notice" role="note">
        <AlertCircle size={17} />
        <p><strong>Simulation only.</strong> The current forecasts are generated by the simulator&apos;s physics-based heuristic. A trained and validated machine-learning model is not connected yet.</p>
      </div>

      {error && (
        <div className="storage-warning" role="alert">
          <span>{error}</span>
          <button type="button" onClick={() => { void refresh(); }}>Retry</button>
        </div>
      )}

      <section className="summary-grid ml-summary-grid" aria-label="Prediction summary">
        <article className="summary-card">
          <span className="summary-icon purple"><BrainCircuit size={20} /></span>
          <div className="summary-content">
            <span className="summary-label">Training Examples Ready</span>
            <strong>{mlPipeline ? mlPipeline.trainingExampleCount : "—"}</strong>
            <small className="muted">Valid simulation examples for {mlPipeline?.horizonHours ?? 6}h forecasts</small>
          </div>
        </article>
        <article className="summary-card">
          <span className="summary-icon blue"><TrendingDown size={20} /></span>
          <div className="summary-content">
            <span className="summary-label">Mean Absolute Error</span>
            <strong>{snapshot?.predictionMae == null ? "—" : `${snapshot.predictionMae.toFixed(1)} pp`}</strong>
            <small className="muted">{evaluatedCount} saved forecasts with actual outcomes</small>
          </div>
        </article>
        <article className="summary-card">
          <span className="summary-icon mint"><Database size={20} /></span>
          <div className="summary-content">
            <span className="summary-label">Saved Forecasts</span>
            <strong>{loading && !snapshot ? "—" : predictions.length}</strong>
            <small className="muted">{latestPrediction?.algorithm ?? "Run an AI-assisted simulation to create forecasts"}</small>
          </div>
        </article>
      </section>

      <section className="panel ml-workflow-panel" aria-label="Machine-learning and forecast workflow">
        <div className="panel-heading ml-history-heading">
          <div><h2>One workflow: data to forecast</h2><p>The saved prediction history and its source data, connected in the same pipeline</p></div>
          <span className={`ml-model-status ${mlPipeline?.modelTrained ? "ready" : ""}`}>
            {mlPipeline?.modelTrained ? "Trained model" : "Training model not connected"}
          </span>
        </div>
        <ol className="ml-workflow-steps">
          <li><span>1</span><div><strong>Simulation readings</strong><small>Sensor + weather features</small></div></li>
          <li><span>2</span><div><strong>{mlPipeline?.trainingExampleCount ?? "—"} training examples</strong><small>Target: {mlPipeline?.target ?? "future simulated soil moisture"}</small></div></li>
          <li><span>3</span><div><strong>{predictions.length} saved forecasts</strong><small>{latestPrediction?.algorithm ?? "No forecast method recorded"}</small></div></li>
        </ol>
        <div className="ml-feature-list"><strong>Input features</strong>{(mlPipeline?.features ?? []).map((feature) => <span key={feature}>{feature.replaceAll("_", " ")}</span>)}</div>
        <div className="ml-plant-coverage">
          <div className="ml-coverage-heading"><strong>Plant profiles in the dataset</strong><span>Details flow in after simulation readings are recorded</span></div>
          {mlPipeline?.trainingExamplesByPlant.length ? (
            <div className="ml-coverage-list">
              {mlPipeline.trainingExamplesByPlant.map((plant) => (
                <article className="ml-coverage-card" key={plant.plantId}>
                  <div><strong>{plant.plantName}</strong><small>{plant.species}</small></div>
                  <span>{plant.exampleCount} examples</span>
                </article>
              ))}
            </div>
          ) : <p className="ml-workflow-note">Add a plant to see its profile here. It will contribute training examples after a simulation records valid readings.</p>}
        </div>
        <p className="ml-workflow-note">Forecast records currently come from the physics-based simulator. The prepared training examples are ready for a future model-training step; no trained model is used to produce these forecasts.</p>
      </section>

      {snapshot && <AIPredictionChart predictions={predictions} />}

      <section className="panel ml-history-panel">
        <div className="panel-heading ml-history-heading">
          <div><h2>Recent saved forecasts</h2><p>Predicted and actual soil moisture values from simulation records</p></div>
          <span className="section-count">{predictions.length} records</span>
        </div>
        {loading && !snapshot ? <p className="ml-state" role="status">Loading prediction records…</p>
          : predictions.length ? (
            <div className="ml-table-scroll">
              <table className="ml-prediction-table">
                <thead><tr><th>Plant</th><th>Forecast made</th><th>Target time</th><th>Predicted</th><th>Actual</th><th>Absolute error</th><th>Method</th></tr></thead>
                <tbody>
                  {predictions.map((prediction) => {
                    const errorValue = prediction.actualMoisture === null
                      ? null
                      : Math.abs(prediction.predictedMoisture - prediction.actualMoisture);
                    return (
                      <tr key={prediction.id}>
                        <td>{prediction.plant}</td>
                        <td>{formatTime(prediction.madeAt)}</td>
                        <td>{formatTime(prediction.targetTime)}</td>
                        <td>{prediction.predictedMoisture.toFixed(1)}%</td>
                        <td>{prediction.actualMoisture === null ? "Pending" : `${prediction.actualMoisture.toFixed(1)}%`}</td>
                        <td>{errorValue === null ? "—" : `${errorValue.toFixed(1)} pp`}</td>
                        <td>{prediction.algorithm}</td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          ) : <p className="ml-state">{error ? "Prediction records are unavailable until the backend connection is restored." : "No forecasts are saved yet. Run an AI-assisted simulation to create prediction records."}</p>}
      </section>
    </div>
  );
}
